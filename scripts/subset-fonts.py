#!/usr/bin/env python3
"""Split the two app fonts into three unicode-range pieces each, so a first visit
downloads only the letters the app's own text uses.

  fonts/ForestSans.woff2   (Pretendard Variable, 2.0 MB)
  fonts/ForestSerif.woff2  (0.3 MB)
    -> public/fonts/<Family>-app.<hash>.woff2   letters found in the app's source text
    -> public/fonts/<Family>-ks.<hash>.woff2    the other everyday Hangul (KS X 1001)
    -> public/fonts/<Family>-rest.<hash>.woff2  everything else in the font
    -> src/presentation/fontFaces.css           the @font-face rules (generated)

The browser picks pieces by unicode-range, so text typed by a teacher or student that
uses a rare letter still renders in the same font; it only costs one more download.
Re-run after large text changes to keep the first piece complete:

  python3 -m venv .venv-fonts && .venv-fonts/bin/pip install fonttools brotli
  .venv-fonts/bin/python scripts/subset-fonts.py
"""
import hashlib
import io
import pathlib
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'public' / 'fonts'
CSS = ROOT / 'src' / 'presentation' / 'fontFaces.css'
FAMILIES = [
    # family, source, font-weight descriptor, split everyday Hangul into its own piece?
    ('ForestSans', ROOT / 'fonts' / 'ForestSans.woff2', '45 920', True),
    # The serif is only used for big titles, which come from the app's own text.
    ('ForestSerif', ROOT / 'fonts' / 'ForestSerif.woff2', '600', False),
]
TEXT_GLOBS = ['index.html', 'src/**/*.ts', 'src/**/*.tsx', 'src/**/*.css', 'src/**/*.json',
              'public/*.svg', 'public/manifest.json', 'supabase/**/*.sql']


def app_chars():
    chars = set()
    for pattern in TEXT_GLOBS:
        for path in ROOT.glob(pattern):
            if path == CSS:
                continue
            chars.update(ord(c) for c in path.read_text(encoding='utf-8', errors='ignore'))
    # Always-on basics: Latin, Latin-1, general punctuation, Hangul jamo used while typing.
    for lo, hi in [(0x20, 0x7E), (0xA0, 0xFF), (0x2010, 0x2027), (0x2030, 0x205E), (0x3131, 0x318E)]:
        chars.update(range(lo, hi + 1))
    return chars


def ks_hangul():
    out = set()
    for lead in range(0xB0, 0xC9):
        for trail in range(0xA1, 0xFF):
            try:
                out.add(ord(bytes([lead, trail]).decode('euc-kr')))
            except UnicodeDecodeError:
                pass
    return out


def ranges(codepoints):
    cps = sorted(codepoints)
    parts, start, prev = [], None, None
    for cp in cps:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            parts.append((start, prev))
            start = prev = cp
    if start is not None:
        parts.append((start, prev))
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in parts)


def make_piece(source, codepoints):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.notdef_outline = True
    options.name_IDs = ['*']
    options.hinting = False
    font = TTFont(source, recalcTimestamp=False)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(codepoints))
    subsetter.subset(font)
    buffer = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buffer)
    return buffer.getvalue()


def main():
    used, ks = app_chars(), ks_hangul()
    rules = ['/* Generated by scripts/subset-fonts.py. Do not edit by hand. */']
    preload = {}
    for family, source, weight, split_everyday in FAMILIES:
        cmap = set(TTFont(source).getBestCmap())
        app = used & cmap
        everyday = (ks & cmap) - app if split_everyday else set()
        rest = cmap - app - everyday
        for old in OUT.glob(f'{family}-*.woff2'):
            old.unlink()
        # A browser tries the pieces from the last rule to the first and downloads a piece only when
        # its unicode-range names the letter. So the catch-all piece comes first and may claim the whole
        # Hangul block (the exact lists after it win), which keeps this file small.
        hangul = set(range(0xAC00, 0xD7A4))
        rest_range = ranges((rest - hangul) | hangul)
        for label, codepoints, declared in [('rest', rest, rest_range), ('ks', everyday, None), ('app', app, None)]:
            if not codepoints:
                continue
            data = make_piece(source, codepoints)
            name = f'{family}-{label}.{hashlib.sha256(data).hexdigest()[:8]}.woff2'
            (OUT / name).write_bytes(data)
            rules.append(
                f"@font-face{{font-family:{family};src:url('/fonts/{name}') format('woff2');"
                f"font-weight:{weight};font-style:normal;font-display:swap;unicode-range:{declared or ranges(codepoints)}}}")
            if label == 'app':
                preload[family] = name
            print(f'{name}: {len(codepoints)} letters, {len(data) // 1024} KB')
    CSS.write_text('\n'.join(rules) + '\n', encoding='utf-8')
    # index.html preloads the first piece of each family; keep its file names in step.
    index = ROOT / 'index.html'
    html = index.read_text(encoding='utf-8')
    for family, name in preload.items():
        html = re.sub(rf'/fonts/{family}(?:-app\.[0-9a-f]+)?\.woff2', f'/fonts/{name}', html)
    index.write_text(html, encoding='utf-8')


if __name__ == '__main__':
    main()
